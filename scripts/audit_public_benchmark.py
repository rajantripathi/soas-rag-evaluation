"""Reproduce descriptive release statistics without private corpora or models."""
from __future__ import annotations

import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path


def audit(rows: list[dict]) -> dict:
    if not rows:
        raise ValueError('Dataset is empty')
    ids = [row['id'] for row in rows]
    if len(set(ids)) != len(ids):
        raise ValueError('Duplicate item IDs')
    # This release has one target per row. Reject other schemas rather than
    # silently treating overlapping multi-target sets as independent clusters.
    if any(len(row['source_doc_ids']) != 1 for row in rows):
        raise ValueError('This audit requires exactly one source target per row')
    by_language = {}
    for language in sorted({row['language'] for row in rows}):
        subset = [row for row in rows if row['language'] == language]
        groups = Counter(row['source_doc_ids'][0] for row in subset)
        by_language[language] = {
            'rows': len(subset),
            'source_targets': len(groups),
            'rows_per_target_distribution': dict(sorted(Counter(groups.values()).items())),
            'flagged_rows': sum(bool(row['quality_flag']) for row in subset),
            'flags': dict(sorted(Counter(row['quality_flag'] for row in subset if row['quality_flag']).items())),
            'missing_source_titles': sum(not row['source_title'] for row in subset),
            'domain_counts': dict(sorted(Counter(row['domain'] for row in subset).items())),
        }
    return {
        'rows': len(rows),
        'language_scoped_source_targets': sum(x['source_targets'] for x in by_language.values()),
        'duplicate_question_rows': len(rows) - len({(row['language'], row['question']) for row in rows}),
        'by_language': by_language,
    }


def render(report: dict) -> str:
    lines = ['# Public benchmark structure audit', '',
             'Generated by `python3 scripts/audit_public_benchmark.py`. This is a structural audit, not a linguistic quality review or a new retrieval experiment.', '',
             f"Input: `{report['input']}`", '', f"SHA-256: `{report['sha256']}`", '',
             '| Language | Rows | Source targets | Flagged rows | Missing titles |',
             '| --- | ---: | ---: | ---: | ---: |']
    for lang, stats in report['by_language'].items():
        lines.append(f"| {lang} | {stats['rows']} | {stats['source_targets']} | {stats['flagged_rows']} | {stats['missing_source_titles']} |")
    lines += ['', f"Total language-scoped targets: **{report['language_scoped_source_targets']}**. Exact duplicate question rows within languages: **{report['duplicate_question_rows']}**.", '',
              '## Target multiplicity', '']
    for lang, stats in report['by_language'].items():
        for size, count in stats['rows_per_target_distribution'].items():
            lines.append(f'- {lang}: {count} targets have {size} question rows each.')
    lines += ['', '## Interpretation', '',
              'Question phrasings sharing a target are related observations. Row count is not the number of independent source targets. Any development/test partition must keep source groups together; a row-level random split can leak the same source into both partitions. Existing evaluation-targeted corpus curation also prevents relabelling a retrospective split as an untouched held-out test.', '',
              'Quality flags are incomplete, so unflagged rows are not a validated clean subset. Missing source titles are metadata gaps; they do not establish that source documents are absent from a corpus. Source identifiers are scoped by language for this audit.', '']
    return '\n'.join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data', type=Path, default=Path('hf_dataset/manual_eval_v5_retrieval_only.jsonl'))
    parser.add_argument('--json', action='store_true')
    args = parser.parse_args()
    data = args.data.read_bytes()
    report = audit([json.loads(line) for line in data.decode('utf-8').splitlines() if line.strip()])
    report.update(input=args.data.as_posix(), sha256=hashlib.sha256(data).hexdigest())
    print(json.dumps(report, indent=2, ensure_ascii=False) if args.json else render(report), end='\n' if args.json else '')


if __name__ == '__main__':
    main()
